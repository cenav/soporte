declare
  l_modified pls_integer := 0;
begin
  for r in (
    select o.nuot_tipoot_codigo, o.nuot_serie, o.numero, o.fecha, o.estado
         , o.formu_art_cod_art as formula
         , o.cant_prog, t.cod_activo_fijo, t.cod_art as anterior
      from pr_ot o
           join pr_ot_det d
                on o.numero = ot_numero
                  and o.nuot_serie = d.ot_nuot_serie
                  and o.nuot_tipoot_codigo = d.ot_nuot_tipoot_codigo
           join tmp_carga_data t on d.art_cod_art = t.cod_art
     where o.nuot_tipoot_codigo = 'PR'
       and o.estado = 1
     order by o.formu_art_cod_art, o.fecha

    )
  loop
    update pr_ot_det
       set art_cod_art = r.cod_activo_fijo
     where ot_nuot_tipoot_codigo = r.nuot_tipoot_codigo
       and ot_nuot_serie = r.nuot_serie
       and ot_numero = r.numero
       and art_cod_art = r.anterior;

    l_modified := sql%rowcount + l_modified;
  end loop;

  dbms_output.put_line('Modified: ' || l_modified);
end;